// Compiles crates/lyric-engine to WebAssembly and writes the bindings into
// frontend/lyric-engine. The output is committed so web builds and tests need
// no Rust toolchain; rerun after changing the crate.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const out = join(root, "frontend", "lyric-engine");
const run = (command, args) =>
  execFileSync(command, args, { cwd: root, stdio: "inherit" });

run("cargo", [
  "build",
  "--locked",
  "--release",
  "-p",
  "lyric-engine",
  "--target",
  "wasm32-unknown-unknown",
]);
const staging = mkdtempSync(join(tmpdir(), "lyric-engine-"));
try {
  run("wasm-bindgen", [
    join(
      root,
      "target",
      "wasm32-unknown-unknown",
      "release",
      "lyric_engine.wasm",
    ),
    "--target",
    "web",
    "--weak-refs",
    "--omit-default-module-path",
    "--out-dir",
    staging,
  ]);
  writeFileSync(
    join(out, "lyric_engine.js"),
    readFileSync(join(staging, "lyric_engine.js")),
  );
  writeFileSync(
    join(out, "lyric_engine.d.ts"),
    readFileSync(join(staging, "lyric_engine.d.ts")),
  );
  const bytes = readFileSync(join(staging, "lyric_engine_bg.wasm"));
  writeFileSync(
    join(out, "wasm.ts"),
    `// Generated by scripts/build-lyric-engine.mjs. Do not edit.\nexport const WASM = "${bytes.toString("base64")}";\n`,
  );
  console.log(`lyric engine: ${bytes.length} bytes of WebAssembly`);
} finally {
  rmSync(staging, { recursive: true, force: true });
}
